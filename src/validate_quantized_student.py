
import pandas as pd
import torch

from sklearn.metrics import (
    accuracy_score,
    f1_score,
    classification_report
)
from transformers import (
    AutoTokenizer,
    AutoModelForSequenceClassification
)

torch.set_num_threads(4)

DATA_PATH = "data/model_dataset_verified.csv"
ORIGINAL_PATH = "models/distilled_student"
QUANTIZED_PATH = (
    "models/distilled_student_int8/quantized_model.pt"
)

print("Loading validation data...")

data = pd.read_csv(
    DATA_PATH,
    encoding="utf-8-sig"
).fillna("")

validation = data[
    data["split"] == "validation"
].copy()

labels = sorted(data["intent"].unique())

print("Validation samples:", len(validation))

print("\nLoading original student...")
original = AutoModelForSequenceClassification.from_pretrained(
    ORIGINAL_PATH
)
original.eval()

print("Loading quantized student...")

# Only load this trusted file generated by our own script.
quantized = torch.load(
    QUANTIZED_PATH,
    map_location="cpu",
    weights_only=False
)
quantized.eval()

tokenizer = AutoTokenizer.from_pretrained(
    ORIGINAL_PATH
)

def predict(model, texts):
    predictions = []

    with torch.no_grad():
        for text in texts:
            inputs = tokenizer(
                text,
                truncation=True,
                max_length=64,
                return_tensors="pt"
            )

            logits = model(**inputs).logits
            predicted_id = int(
                logits.argmax(dim=-1).item()
            )

            predictions.append(labels[predicted_id])

    return predictions

texts = validation["text"].tolist()
true_labels = validation["intent"].tolist()

print("\nRunning original student predictions...")
original_predictions = predict(original, texts)

print("Running INT8 student predictions...")
quantized_predictions = predict(quantized, texts)

print("\nVALIDATION COMPARISON")
print("=" * 55)

for name, predictions in [
    ("Original student", original_predictions),
    ("INT8 student", quantized_predictions)
]:
    accuracy = accuracy_score(
        true_labels, predictions
    )

    macro_f1 = f1_score(
        true_labels,
        predictions,
        labels=labels,
        average="macro",
        zero_division=0
    )

    print(
        f"{name}: accuracy={accuracy:.4f}, "
        f"macro F1={macro_f1:.4f}"
    )

agreement = sum(
    a == b
    for a, b in zip(
        original_predictions,
        quantized_predictions
    )
)

print(
    "\nPrediction agreement:",
    f"{agreement}/{len(texts)}"
)

print("\nINT8 classification report:")
print(
    classification_report(
        true_labels,
        quantized_predictions,
        labels=labels,
        zero_division=0
    )
)

pd.DataFrame({
    "text": texts,
    "language": validation["language"].tolist(),
    "true_intent": true_labels,
    "original_prediction": original_predictions,
    "int8_prediction": quantized_predictions
}).to_csv(
    "results/quantization_validation_comparison.csv",
    index=False,
    encoding="utf-8-sig"
)

print(
    "\nSaved: "
    "results/quantization_validation_comparison.csv"
)
